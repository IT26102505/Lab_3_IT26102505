#include <stdio.h>

int main (void)

{
	double height,cmeters,mass,power_watts,power_megawatts,work;
	const double effi = 0.9;//efficency is ninety percent
	const double gravi = 9.8;


	printf("Enter the height of the dam in meters: ");
	scanf("%lf",&height);
	printf("\nEnter the number of cubic meters of water that are projected per second: ");
	scanf("%lf",&cmeters);
	
	//calculations based on given formulas
	mass = 1000*cmeters;  //mass of 1 cubic meter is 1000kg
	work = mass*gravi*height;	
	power_watts = effi*work;
	power_megawatts = power_watts/1000000.0;
   

	printf("Predicted power generated by the hydroelectric dam:%.2f megawatts\n",power_megawatts);

	return 0;

}
